/* ------------------------------------------------- library auto-updater */
/* The library files are regenerated whenever the data changes. This watcher
   polls data/index.json once a minute and refreshes the page data the moment
   a newer export lands — no manual reload needed. */
let libStamp = null;
let libWatchStarted = false;

function libToastEl() {
  let t = document.getElementById("lib-toast");
  if (!t) {
    t = document.createElement("div");
    t.id = "lib-toast";
    t.className = "lib-toast";
    t.hidden = true;
    document.body.appendChild(t);
  }
  return t;
}
function hideLibToast() {
  const t = document.getElementById("lib-toast");
  if (t) t.hidden = true;
}
function showLibToast(msg, withRefresh) {
  const t = libToastEl();
  t.innerHTML = "";
  const s = document.createElement("span");
  s.textContent = msg;
  t.appendChild(s);
  if (withRefresh) {
    const b = document.createElement("button");
    b.type = "button";
    b.className = "mini-btn";
    b.textContent = "Refresh now";
    b.addEventListener("click", async () => { hideLibToast(); await doLibRefresh(); });
    t.appendChild(b);
  }
  t.hidden = false;
  clearTimeout(showLibToast._t);
  if (!withRefresh) showLibToast._t = setTimeout(hideLibToast, 5000);
}

async function doLibRefresh() {
  let stamp = null;
  try {
    const r = await fetch(libURL("data/index.json") + "?t=" + Date.now());
    if (r.ok) stamp = (await r.json()).exported_at || null;
  } catch { /* keep the old stamp */ }
  for (const k of Object.keys(libCache)) delete libCache[k];
  for (const k of Object.keys(libData)) delete libData[k];
  if (stamp) libStamp = stamp;
  /* Bypass browser/CDN caches for this reload — the rebuilt views may not
     have propagated to edge caches yet under their normal URLs. */
  libFreshFetch = true;
  try { await route(); }
  finally { libFreshFetch = false; }
}

/* After a local write, watch for the rebuilt export and refresh the moment
   it lands — the page never sits on stale data waiting for the 60s poll. */
let awaitUpdateTimer = null;
function awaitLibraryUpdate() {
  const preStamp = libStamp;
  if (awaitUpdateTimer) clearInterval(awaitUpdateTimer);
  let tries = 0;
  const tick = async () => {
    tries++;
    if (tries > 18) { clearInterval(awaitUpdateTimer); awaitUpdateTimer = null; return; }
    try {
      const r = await fetch(libURL("data/index.json") + "?t=" + Date.now());
      if (!r.ok) return;
      const idx = await r.json();
      if (idx.exported_at && idx.exported_at !== preStamp) {
        clearInterval(awaitUpdateTimer); awaitUpdateTimer = null;
        if (!document.querySelector(".edit-panel:not([hidden])")) {
          await doLibRefresh();
          showLibToast("Library updated.");
        } else {
          showLibToast("The library was updated.", true);
        }
      }
    } catch { /* try again next tick */ }
  };
  awaitUpdateTimer = setInterval(tick, 10000);
  tick();
}

/* After a successful write the file cache is stale until the next export.
   Patch the cached copies immediately so the re-rendered page shows the
   just-saved values instead of looking reverted. */
function optimisticPatch(entityType, entityId, changes) {
  const vals = {};
  for (const f of changes) vals[f.name] = f.value;
  const patchOne = (o) => {
    if (!o || typeof o !== "object" || Array.isArray(o)) return;
    if (o.id === entityId) {
      for (const k of Object.keys(vals)) o[k] = vals[k];
    }
    if (entityType === "artist" && vals.canonical_name !== undefined) {
      const aid = o.artist_id || (o.artists && o.artists.id);
      if (aid === entityId && o.artists && typeof o.artists === "object") {
        o.artists.canonical_name = vals.canonical_name;
      }
    }
    for (const v of Object.values(o)) {
      if (Array.isArray(v)) v.forEach(patchOne);
      else patchOne(v);
    }
  };
  for (const d of Object.values(libData)) patchOne(d);
}

/* Keep a release's slim catalog/artwork copies consistent after an artwork
   role change or add (the full rows are patched by optimisticPatch). */
function syncReleaseArtwork(releaseId) {
  const rv = libData[`data/views/release/${releaseId}.json`];
  const cat = libData["data/views/catalog.json"];
  if (!rv || !rv.artwork || !cat) return;
  const canon = rv.artwork.find(x => x.role === "canonical");
  const slim = canon ? [{ id: canon.id, source_url: canon.source_url, stored_path: canon.stored_path, role: "canonical" }] : [];
  const cr = cat.releases.find(x => x.id === releaseId);
  if (cr) cr.artwork = slim;
  for (const d of Object.values(libData)) {
    const rels = d && d.releases;
    if (Array.isArray(rels)) {
      const m = rels.find(x => x.id === releaseId);
      if (m) m.artwork = slim;
    }
  }
}

async function checkLibUpdate() {
  if (document.hidden) return;
  let idx;
  try {
    const r = await fetch(libURL("data/index.json") + "?t=" + Date.now());
    if (!r.ok) return;
    idx = await r.json();
  } catch { return; }
  if (!idx || !idx.exported_at) return;
  if (!libStamp) { libStamp = idx.exported_at; return; }
  if (idx.exported_at === libStamp) return;
  /* A newer export landed. Don't yank the page out from under an open editor. */
  if (document.querySelector(".edit-panel:not([hidden])")) {
    showLibToast("The library was updated.", true);
    return;
  }
  await doLibRefresh();
  showLibToast("Library updated.");
}

function startLibWatcher() {
  if (libWatchStarted) return;
  libWatchStarted = true;
  setInterval(checkLibUpdate, 60000);
}

