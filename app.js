function esc(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

function chip(conf) {
  const c = CONF_LABEL[conf] ? conf : "unknown";
  return `<span class="st st-${c}"><i></i>${esc(CONF_LABEL[c])}</span>`;
}

function editionChip(ed) {
  if (!ed || ed === "original") return "";
  return `<span class="st st-edition">${esc(ed)}</span>`;
}

/* Effective release status: a manual release_status always wins; otherwise
   it's checked automatically from dates (a future date, or no date and no
   year at all, means unreleased). */
function releaseStatus(r) {
  if (r.release_status === "unreleased") return "unreleased";
  if (r.release_status === "released") return "released";
  const today = new Date().toISOString().slice(0, 10);
  if (r.release_date && r.release_date > today) return "unreleased";
  if (!r.release_date && !r.release_year) return "unreleased";
  return "released";
}
function unreleasedTag(r) {
  return releaseStatus(r) === "unreleased" ? `<span class="st st-unreleased"><i></i>Unreleased</span>` : "";
}

/* Images fade in over a skeleton shimmer. The skeleton background shows
   while the image loads; a broken image collapses silently to it. */
function im(u, cls, alt) {
  return `<img class="${cls} iv" src="${esc(u)}" alt="${esc(alt || "")}" loading="lazy" onload="this.classList.add('ld')" onerror="this.classList.add('err')">`;
}

function fmtDate(iso) {
  if (!iso) return "";
  const d = new Date(iso);
  return isNaN(d) ? esc(iso) : d.toLocaleDateString("en-US", { year: "numeric", month: "short", day: "numeric" });
}

function fmtDur(ms) {
  if (!ms) return "";
  const s = Math.round(ms / 1000);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

function artUrl(a) {
  if (!a) return "";
  if (a.stored_path) return `${cfg.SUPABASE_URL}/storage/v1/object/public/artwork/${a.stored_path}`;
  if (a.source_url) return a.source_url;
  return "";
}

async function api(path, opts = {}) {
  /* authEnsure() refreshes the admin session when the access token has
     expired, and drops back to the public anon key when signed out or
     when the refresh fails — so a stale token can never 401 every read. */
  const userTok = await authEnsure();
  const headers = { apikey: KEY, Authorization: `Bearer ${userTok || KEY}`, Accept: "application/json" };
  if (opts.count) {
    headers.Prefer = "count=exact";
    headers.Range = "0-0";
    headers["Range-Unit"] = "items";
  }
  const fetchOpts = { headers };
  if (opts.method) {
    fetchOpts.method = opts.method;
    headers["Content-Type"] = "application/json";
    if (opts.body !== undefined) fetchOpts.body = JSON.stringify(opts.body);
    if (opts.method === "POST") headers.Prefer = "return=representation";
  }
  const res = await fetch(`${BASE}/${path}`, fetchOpts);
  if (!res.ok) throw new Error(`Database ${opts.method || "read"} failed (${res.status})`);
  if (opts.count) {
    const total = parseInt((res.headers.get("content-range") || "").split("/")[1], 10);
    return isNaN(total) ? 0 : total;
  }
  const text = await res.text();
  return text ? JSON.parse(text) : null;
}

